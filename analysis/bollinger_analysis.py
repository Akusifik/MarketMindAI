def analyze_bollinger(price, upper, lower):

    if price >= upper:
        return {
            "status": "upper",
            "signal": "SELL",
            "message": "🔴 Цена у верхней полосы",
            "score": -1,
            "reasons": [
                f"Текущая цена = {price:.2f}.",
                f"Верхняя полоса Боллинджера = {upper:.2f}.",
                "Цена достигла или превысила верхнюю полосу.",
                "Это может указывать на перекупленность и возможную коррекцию."
            ]
        }

    elif price <= lower:
        return {
            "status": "lower",
            "signal": "BUY",
            "message": "🟢 Цена у нижней полосы",
            "score": 1,
            "reasons": [
                f"Текущая цена = {price:.2f}.",
                f"Нижняя полоса Боллинджера = {lower:.2f}.",
                "Цена достигла или опустилась ниже нижней полосы.",
                "Это может указывать на перепроданность и возможный отскок."
            ]
        }

    return {
        "status": "inside",
        "signal": "NEUTRAL",
        "message": "🟡 Цена внутри диапазона",
        "score": 0,
        "reasons": [
            f"Текущая цена = {price:.2f}.",
            f"Диапазон полос: {lower:.2f} — {upper:.2f}.",
            "Цена находится между верхней и нижней полосами.",
            "Экстремальных отклонений от среднего значения не наблюдается."
        ]
    }